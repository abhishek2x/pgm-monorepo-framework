class MetricsCalculator:
    """
    Calculates key metrics for the research benchmark.
    """
    
    @staticmethod
    def calculate_tcr(successful_tasks: int, total_tasks: int) -> float:
        """Task Completion Rate"""
        if total_tasks == 0:
            return 0.0
        return successful_tasks / total_tasks
        
    @staticmethod
    def calculate_cptr(tasks_benefiting: int, tasks_with_knowledge_available: int) -> float:
        """
        Cross-User Procedural Transfer Rate.
        Measures successful tasks benefiting from knowledge generated by ANOTHER user.
        """
        if tasks_with_knowledge_available == 0:
            return 0.0
        return tasks_benefiting / tasks_with_knowledge_available

    @staticmethod
    def print_summary_table(results: dict):
        """Prints a mock success-rate table"""
        print("-" * 50)
        print(f"{'Baseline':<20} | {'TCR':<10} | {'CPTR':<10}")
        print("-" * 50)
        for baseline, data in results.items():
            tcr = MetricsCalculator.calculate_tcr(data['success'], data['total'])
            cptr = MetricsCalculator.calculate_cptr(data['transfers'], data['opportunities'])
            print(f"{baseline:<20} | {tcr:<10.2f} | {cptr:<10.2f}")
        print("-" * 50)
